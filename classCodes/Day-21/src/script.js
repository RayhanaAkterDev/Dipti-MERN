const fruites = ["mango", 'apple', 'banana'];

// array destructuring
const [frt1, frt2] = fruites;
console.log(frt1);
console.log(frt2);

const info = {
    name: 'sumaya',
    age: 25,
}

// object destructuring
const { name, age } = info;
console.log(name);
console.log(age);

console.log(info.name);